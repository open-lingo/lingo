#!/usr/bin/env node
/**
 * Ingest the 국립국어원 (National Institute of Korean Language) open-government
 * Korean corpus into `KO_FREQUENCY_ATOMS`.
 *
 *   출처: 국립국어원 (National Institute of Korean Language) — KOGL Type 1
 *   (공공누리 제1유형): commercial use OK, attribution required, NO share-alike.
 *
 * Source files (see scripts/data/ko-frequency-raw/SOURCES.txt for provenance):
 *   • learner-vocab-list.txt        한국어 학습용 어휘 목록 (2003), 5,965 graded
 *                                   words. EUC-KR, TAB. Columns:
 *                                   순위 · 단어 · 품사 · 풀이(Hanja) · 등급(A/B/C).
 *                                   THIS IS THE SPINE.
 *   • freq-2002/단어_빈도색인.txt   현대 국어 사용 빈도 조사 (2002), 58,437 words
 *                                   with real corpus counts. EUC-KR, TAB.
 *                                   Joined by surface for real frequency ranking.
 *
 * What is generated vs. sourced:
 *   • surface / POS / Hanja gloss / grade  → from the gov data (authoritative).
 *   • frequencyRank / unlockModule         → derived: rank by joined corpus
 *                                            frequency (fallback: learner 순위),
 *                                            module via `frequencyRankToModule`
 *                                            (the ONE gating source of truth,
 *                                            imported from frequencyTypes.ts).
 *   • reading (RR romanization)            → GENERATED by romanizeKorean
 *                                            (ko/romanization/hangulRomanize.ts).
 *   • meaningEn (English gloss)            → GENERATED (KO→EN), curated per-word
 *                                            in scripts/data/ko-glosses.json.
 *                                            Words absent from that map are
 *                                            OMITTED (ship fewer, all correct).
 *   • conjugation link                     → attached only where the surface is
 *                                            a real KO_LEMMAS lemma (exact match).
 *
 * The TS engine (romanizer, frequency gating) is imported by transpiling the
 * source with esbuild at ingest time — no formula is duplicated, so gating +
 * romanization stay in lockstep with the app.
 *
 * Usage:
 *   node scripts/ingest-ko-frequency.mjs               # (re)generate the registry
 *   node scripts/ingest-ko-frequency.mjs --candidates  # emit the gloss worklist
 *
 * Re-run command of record: `node scripts/ingest-ko-frequency.mjs`.
 */
import { readFileSync, writeFileSync, existsSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { transformSync } from "esbuild";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, "..");
const RAW = join(HERE, "data", "ko-frequency-raw");
const GLOSS_PATH = join(HERE, "data", "ko-glosses.json");
const CANDIDATES_PATH = join(HERE, "data", "ko-frequency-candidates.json");
const OUT_PATH = join(REPO, "src", "features", "languages", "ko", "frequencyAtoms.ts");

const KO_FREQ_LAST_MODULE = 27; // KO has 27 content modules — its unlock ceiling.

// ─────────────────────────────────────────────────────────────────────────
// Import the TS single-sources-of-truth (frequency gating + RR romanizer) by
// transpiling them with esbuild. Both are import-light (type-only / no imports),
// so a per-file transform is sufficient — no bundling / alias resolution needed.
// ─────────────────────────────────────────────────────────────────────────
async function loadTsModule(relPath) {
  const src = readFileSync(join(REPO, relPath), "utf8");
  const { code } = transformSync(src, { loader: "ts", format: "esm" });
  const dir = mkdtempSync(join(tmpdir(), "ko-ingest-"));
  const file = join(dir, "mod.mjs");
  writeFileSync(file, code);
  return import(pathToFileURL(file).href);
}

// ─────────────────────────────────────────────────────────────────────────
// EUC-KR decode (Node ships full-icu; TextDecoder handles euc-kr directly).
// ─────────────────────────────────────────────────────────────────────────
const eucKr = new TextDecoder("euc-kr");
function readEucKr(path) {
  return eucKr.decode(readFileSync(path));
}

// Korean single-char POS label → shared PartOfSpeech taxonomy.
// (Learner-list codes; see SOURCES.txt.)
const POS_MAP = {
  명: "noun", // 명사
  동: "verb", // 동사
  형: "adjective", // 형용사 (descriptive verb)
  부: "adverb", // 부사
  의: "noun", // 의존명사 (dependent noun)
  관: "determiner", // 관형사
  고: "proper-noun", // 고유명사
  수: "number", // 수사
  대: "pronoun", // 대명사
  감: "interjection", // 감탄사
  보: "verb", // 보조용언 (auxiliary predicate)
  불: "other", // 불규칙/준말 (contracted colloquial forms: 걔, 얘, 그래도…)
};

// Proper nouns (place / personal names) add little to a general vocab deck.
const DROP_POS = new Set(["proper-noun"]);

const HANGUL = /[가-힣]/;
const TRAIL_DIGITS = /\d+$/;
const stripHomograph = (w) => w.replace(TRAIL_DIGITS, "");
const parseFreq = (s) => Number(String(s).replace(/,/g, "").trim()) || 0;

// ── Build surface → total corpus frequency from the 2002 frequency index. ──
function loadCorpusFrequency() {
  const text = readEucKr(join(RAW, "freq-2002", "단어_빈도색인.txt"));
  const lines = text.split(/\r?\n/).filter((l) => l.trim());
  const freq = new Map(); // stripped surface → summed 빈도
  for (const line of lines.slice(1)) {
    // cols: 차례 항목 풀이 품사 빈도 …
    const c = line.split("\t");
    const item = (c[1] ?? "").trim();
    if (!item || !HANGUL.test(item)) continue;
    const surface = stripHomograph(item);
    const f = parseFreq(c[4]);
    if (!f) continue;
    freq.set(surface, (freq.get(surface) ?? 0) + f);
  }
  return freq;
}

// ── Parse the graded learner list into the spine. ──
// The list carries one row per (word, POS) sense, so a homograph-suffixed word
// (있다01, 그01) can repeat with different POS tags. We collapse to ONE atom per
// distinct word (keyed by the digit-suffixed rawWord, which is the corpus's own
// homograph key: 가구03=家口 stays separate from 가구04=家具) and keep the first
// (primary) sense's POS + Hanja.
function loadLearnerSpine() {
  const text = readEucKr(join(RAW, "learner-vocab-list.txt"));
  const lines = text.split(/\r?\n/).filter((l) => l.trim());
  const byWord = new Map();
  for (const line of lines.slice(1)) {
    // cols: 순위 단어 품사 풀이(Hanja) 등급
    const c = line.split("\t");
    const nativeRank = Number((c[0] ?? "").trim()) || Number.MAX_SAFE_INTEGER;
    const rawWord = (c[1] ?? "").trim();
    const posChar = (c[2] ?? "").trim();
    const hanja = (c[3] ?? "").trim();
    const grade = (c[4] ?? "").trim();
    if (!rawWord || !HANGUL.test(rawWord)) continue;
    const surface = stripHomograph(rawWord);
    if (!surface) continue;
    if (byWord.has(rawWord)) continue; // keep the primary (first) sense
    const pos = POS_MAP[posChar] ?? "other";
    byWord.set(rawWord, { nativeRank, rawWord, surface, posChar, pos, hanja, grade });
  }
  return [...byWord.values()];
}

async function main() {
  const emitCandidates = process.argv.includes("--candidates");

  const [{ frequencyRankToModule }, { romanizeKorean }] = await Promise.all([
    loadTsModule("src/features/languages/frequencyTypes.ts"),
    loadTsModule("src/features/languages/ko/romanization/hangulRomanize.ts"),
  ]);

  // KO_LEMMAS (id / lemma / cls) extracted from the authored conjugation table.
  // Data-only read of the single source of truth; the frequencyAtoms test
  // re-validates every link against the real KO_LEMMAS import.
  const lemmaSrc = readFileSync(
    join(REPO, "src/features/languages/ko/conjugationTables.ts"),
    "utf8",
  );
  const lemmaByLemma = new Map();
  const lemmaRe =
    /\{\s*id:\s*"([^"]+)",\s*lemma:\s*"([^"]+)",[^}]*?cls:\s*"([^"]+)"/g;
  for (let m; (m = lemmaRe.exec(lemmaSrc)); ) {
    lemmaByLemma.set(m[2], { class: m[3], lemmaId: m[1] });
  }

  const corpusFreq = loadCorpusFrequency();
  const spine = loadLearnerSpine();

  // Annotate with corpus frequency; drop unwanted POS.
  const annotated = spine
    .filter((r) => !DROP_POS.has(r.pos))
    .map((r) => ({ ...r, corpusFreq: corpusFreq.get(r.surface) ?? 0 }));

  // Rank: words with a corpus count first (by count desc), then the rest by the
  // learner-list 순위 (fallback). Tie-break deterministically by rawWord.
  annotated.sort((a, b) => {
    const ah = a.corpusFreq > 0 ? 1 : 0;
    const bh = b.corpusFreq > 0 ? 1 : 0;
    if (ah !== bh) return bh - ah;
    if (ah) {
      if (b.corpusFreq !== a.corpusFreq) return b.corpusFreq - a.corpusFreq;
    } else if (a.nativeRank !== b.nativeRank) {
      return a.nativeRank - b.nativeRank;
    }
    return a.rawWord.localeCompare(b.rawWord, "ko");
  });

  if (emitCandidates) {
    // The gloss worklist: every graded word, in frequency order, with the hints
    // a translator needs (surface, POS, Hanja, grade). Feeds ko-glosses.json.
    const candidates = annotated.map((r, i) => ({
      order: i + 1,
      rawWord: r.rawWord,
      surface: r.surface,
      pos: r.pos,
      hanja: r.hanja,
      grade: r.grade,
      corpusFreq: r.corpusFreq,
    }));
    writeFileSync(CANDIDATES_PATH, JSON.stringify(candidates, null, 2));
    console.error(`wrote ${candidates.length} candidates → ${CANDIDATES_PATH}`);
    return;
  }

  // ── Load curated English glosses (KO→EN). Keyed by rawWord (homograph-aware);
  //    falls back to the bare surface key for convenience. ──
  if (!existsSync(GLOSS_PATH)) {
    console.error(
      `missing ${GLOSS_PATH} — run with --candidates, author glosses, then re-run.`,
    );
    process.exit(1);
  }
  const glosses = JSON.parse(readFileSync(GLOSS_PATH, "utf8"));
  const glossFor = (r) => {
    const g = glosses[r.rawWord] ?? glosses[r.surface];
    return typeof g === "string" ? g.trim() : "";
  };

  // Keep only words we can gloss accurately. Re-rank densely (1..N) over the
  // shipped set — since it is the highest-frequency graded core, this preserves
  // frequency order while giving a clean unlockModule spread.
  const shipped = annotated.filter((r) => glossFor(r).length > 0);

  // Disambiguate ids for colliding surfaces (homographs, e.g. 가구03=家口 vs
  // 가구04=家具). Non-colliding surfaces keep the plain `ko:<surface>` id.
  const bySurface = new Map();
  for (const r of shipped) {
    if (!bySurface.has(r.surface)) bySurface.set(r.surface, []);
    bySurface.get(r.surface).push(r);
  }
  const idFor = (r) => {
    const group = bySurface.get(r.surface);
    if (group.length === 1) return `ko:${r.surface}`;
    const digit = (r.rawWord.match(TRAIL_DIGITS) ?? [])[0];
    const suffix = digit ?? String(group.indexOf(r) + 1);
    return `ko:${r.surface}-${suffix}`;
  };

  const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  const atoms = shipped.map((r, i) => {
    const frequencyRank = i + 1;
    const unlockModule = frequencyRankToModule(frequencyRank, {
      lastModule: KO_FREQ_LAST_MODULE,
    });
    return {
      id: idFor(r),
      surface: r.surface,
      reading: romanizeKorean(r.surface),
      meaningEn: glossFor(r),
      pos: r.pos,
      frequencyRank,
      unlockModule,
      // Only predicates conjugate — guard against a non-verb/adjective homograph
      // (e.g. adverb 보다 "more") colliding with a lemma surface (verb 보다 "see").
      conjugation:
        r.pos === "verb" || r.pos === "adjective"
          ? lemmaByLemma.get(r.surface)
          : undefined,
    };
  });

  const conjCount = atoms.filter((a) => a.conjugation).length;
  const moduleDist = {};
  for (const a of atoms) moduleDist[a.unlockModule] = (moduleDist[a.unlockModule] ?? 0) + 1;

  const body = atoms
    .map((a) => {
      const conj = a.conjugation
        ? `, conjugation: { class: "${a.conjugation.class}", lemmaId: "${a.conjugation.lemmaId}" }`
        : "";
      return (
        `  { id: "${esc(a.id)}", surface: "${esc(a.surface)}", ` +
        `reading: "${esc(a.reading)}", meaningEn: "${esc(a.meaningEn)}", ` +
        `pos: "${a.pos}", frequencyRank: ${a.frequencyRank}, ` +
        `unlockModule: ${a.unlockModule}${conj}, source: "freq" },`
      );
    })
    .join("\n");

  const header = `/**
 * Korean frequency ("optional") vocabulary — the REAL registry.
 *
 * 출처: 국립국어원 (National Institute of Korean Language) — KOGL Type 1
 * (공공누리 제1유형): commercial use OK, attribution required, no share-alike.
 *
 * GENERATED by scripts/ingest-ko-frequency.mjs — do not hand-edit. Re-run:
 *   node scripts/ingest-ko-frequency.mjs
 *
 * Sources:
 *   • 한국어 학습용 어휘 목록 (2003)   graded learner spine (surface / POS / Hanja / grade)
 *   • 현대 국어 사용 빈도 조사 (2002)  corpus frequency counts (frequency ranking)
 *
 * Generated fields: \`reading\` is Revised Romanization from the app's
 * \`romanizeKorean\` engine; \`meaningEn\` is a curated KO→EN gloss
 * (scripts/data/ko-glosses.json — words we cannot gloss accurately are OMITTED,
 * not guessed). \`frequencyRank\` ranks by joined corpus frequency and
 * \`unlockModule\` is baked from the shared \`frequencyRankToModule\`, so gating
 * matches the rest of the app. Conjugation links are attached only where the
 * surface is a real \`KO_LEMMAS\` lemma.
 *
 * Atoms: ${atoms.length}. Conjugation-linked: ${conjCount}.
 */
import type { KoConjugationLink } from "./courseAtoms";
import type { FrequencyAtom } from "../frequencyTypes";

/** KO has 27 content modules — its true upper unlock bound. */
export const KO_FREQ_LAST_MODULE = ${KO_FREQ_LAST_MODULE};

export const KO_FREQUENCY_ATOMS: ReadonlyArray<FrequencyAtom<KoConjugationLink>> = [
`;

  const out = `${header}${body}\n];\n`;
  writeFileSync(OUT_PATH, out);
  console.error(
    `wrote ${atoms.length} atoms → ${OUT_PATH}\n` +
      `  conjugation-linked: ${conjCount}\n` +
      `  unlockModule distribution: ${JSON.stringify(moduleDist)}`,
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
